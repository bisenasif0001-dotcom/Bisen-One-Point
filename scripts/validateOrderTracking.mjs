import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {MemoryRouter} from 'react-router-dom';
import {createServer} from 'vite';
const server=await createServer({server:{middlewareMode:true,hmr:false}});
const memory=(initial=null)=>{const map=new Map(initial===null?[]:[['alnoor_orders',initial]]);return {getItem:key=>map.get(key)??null,setItem:(key,value)=>map.set(key,value)};};
try {
  const storage=await server.ssrLoadModule('/src/utils/orderStorage.js');
  const {default:Page,TrackingOrderDetails,OrderSummarySheet}=await server.ssrLoadModule('/src/pages/TrackOrderPage.jsx');
  const {BUSINESS_CONFIG,getWhatsAppUrl}=await server.ssrLoadModule('/src/data/businessConfig.js');
  const {buildOrderConfirmationMessage}=await server.ssrLoadModule('/src/utils/orderRequestMessage.js');
  const {parseOrderSearch,normaliseOrderPhone,normaliseStoredOrder,readOrderStore,savePlacedOrder,findOrders,findOrder,buildOrderStatusMessage}=storage;
  const request={orderId:'ALN-WA-204903',placedAt:'2026-11-03T08:00:00Z',items:[{type:'custom_frame',title:'QA request: personal frame',size:'A4',finish:'Regal Noir',price:599,quantity:2}],subtotal:1198,discountAmount:0,shippingFee:0,grandTotal:1198,customer:{name:'QA Customer',phone:'+91 90000 00000',email:'qa@example.test',address:'Test address',city:'Lucknow',state:'Uttar Pradesh',pincode:'226022',cardNumber:'do-not-save',cardCvv:'do-not-save'},paymentMethod:'whatsapp'};
  assert.deepEqual(parseOrderSearch(' #aln - wa - 204903 '),{type:'id',value:'ALN-WA-204903'});
  assert.deepEqual(parseOrderSearch('aln-123456'),{type:'id',value:'ALN-123456'});
  for(const query of ['', '123','99999','900000000','5000000000','ALN-WA-123','<script>','1e10']) assert.ok(parseOrderSearch(query).error);
  for(const query of ['9000000000','+91 90000 00000','09000000000','919000000000']) assert.equal(normaliseOrderPhone(query),'9000000000');
  const store=memory();
  assert.equal(readOrderStore(store).orders.length,0);
  const saved=savePlacedOrder(request,store);
  assert.equal(saved.persisted,true);
  assert.equal(Date.parse(saved.placedAt),Date.parse(request.placedAt));
  assert.equal(saved.payment.isPaid,false);
  assert.equal(saved.currentStageStep,0);
  assert.equal(saved.delivery.awb,null);
  assert.equal(saved.delivery.courier,null);
  assert.equal(saved.delivery.estimatedArrival,null);
  assert.equal(saved.shippingFee,0);
  assert.ok(!JSON.stringify(readOrderStore(store)).includes('do-not-save'));
  assert.equal(findOrders('#aln-wa-204903',readOrderStore(store).orders).length,1);
  assert.equal(findOrders('9000000000',readOrderStore(store).orders).length,1);
  assert.equal(findOrders('0000',readOrderStore(store).orders).length,0,'Never match partial mobile numbers');
  assert.equal(findOrders('ALN-999999',readOrderStore(store).orders).length,0,'Never invent an order');
  assert.equal(findOrder('ALN-999999'),null);
  savePlacedOrder({...request,grandTotal:0,subtotal:0,items:[]},store);
  assert.equal(readOrderStore(store).orders.length,1);
  assert.equal(readOrderStore(store).orders[0].grandTotal,0,'Preserve zero totals');
  savePlacedOrder({...request,orderId:'ALN-123456'},store);
  assert.equal(findOrders('+91 9000000000',readOrderStore(store).orders).length,2);
  const legacy=normaliseStoredOrder({...request,schemaVersion:undefined,currentStageStep:5,statusLabel:'Delivered',payment:{isPaid:true,status:'Paid Online (Verified)'},delivery:{awb:'invented',courier:'invented',estimatedArrival:'tomorrow'}});
  assert.equal(legacy.currentStageStep,0);
  assert.equal(legacy.payment.isPaid,false);
  assert.equal(legacy.delivery.awb,null);
  assert.equal(legacy.customer.city,'Lucknow');
  const noAddress=normaliseStoredOrder({orderId:'ALN-123456'});
  assert.equal(noAddress.customer.city,'');
  assert.equal(noAddress.grandTotal,null);
  assert.equal(noAddress.placedAt,null);
  assert.equal(normaliseStoredOrder({orderId:'bad'}),null);
  for(const value of ['{broken', '{}','null','42']) {
    const broken=memory(value);
    const before=broken.getItem('alnoor_orders');
    assert.notEqual(readOrderStore(broken).status,'ready');
    assert.equal(savePlacedOrder(request,broken).persisted,false);
    assert.equal(broken.getItem('alnoor_orders'),before,'Preserve damaged history');
  }
  const mixed=memory(JSON.stringify([request,null,{id:'bad'},request]));
  assert.equal(readOrderStore(mixed).status,'partial');
  assert.equal(readOrderStore(mixed).orders.length,1);
  assert.equal(savePlacedOrder(request,{getItem:()=>null,setItem:()=>{throw new Error('quota');}}).persisted,false);
  assert.equal(readOrderStore({getItem:()=>{throw new Error('blocked');}}).status,'unavailable');
  assert.equal(normaliseStoredOrder({...request,grandTotal:Infinity}).grandTotal,null);
  const render=element=>renderToStaticMarkup(React.createElement(MemoryRouter,null,element));
  const details=render(React.createElement(TrackingOrderDetails,{order:saved,onSummary:()=>{}}));
  const summary=render(React.createElement(OrderSummarySheet,{order:saved}));
  assert.ok(details.includes('Studio confirmation pending'));
  assert.ok(details.includes('QA request: personal frame'));
  assert.ok(details.includes('₹1,198'));
  assert.ok(summary.includes('Payment not verified by this page'));
  assert.ok(!summary.includes('Official Studio Invoice'));
  assert.ok(!details.includes('AWB-') && !details.includes('Paid Online (Verified)'));
  const confirmation=buildOrderConfirmationMessage(saved);
  assert.ok(confirmation.includes(request.customer.name) && confirmation.includes(request.customer.address));
  assert.ok(confirmation.includes(request.items[0].title) && confirmation.includes('Quantity: 2'));
  assert.ok(confirmation.includes('Checkout total: ₹1,198'));
  assert.ok(confirmation.includes('payment verification') && !confirmation.includes('Paid Online'));
  const page=render(React.createElement(Page));
  assert.equal((page.match(/<h1(?:\s|>)/g)||[]).length,1);
  assert.ok(!page.includes('Valued Customer') && !page.includes('Delhivery'));
  for(const query of ['ALN-WA-204903','+91 9000000000','']) {
    const message=buildOrderStatusMessage(query);
    const url=new URL(getWhatsAppUrl(message));
    assert.equal(url.pathname,`/${BUSINESS_CONFIG.contact.whatsapp}`);
    assert.equal(url.searchParams.get('text'),message);
  }
  console.log('Validated real saved-order matching; exact ID/mobile lookup; no fabricated payment/dispatch/status; legacy records; multi-order phone search; corrupt/blocked/quota storage; zero totals; summary rendering; WhatsApp destination.');
} finally {await server.close();}
